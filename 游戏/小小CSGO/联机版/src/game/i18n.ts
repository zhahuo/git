const messages: Record<Language, Record<MessageKey, string>> = { zh, en, ja, ko };

export const useLanguageStore = create<{ language: Language; setLanguage: (language: Language) => void }>((set) => ({
  language: readStoredLanguage(),
  setLanguage: (language) => {
    if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, language);
    set({ language });
  },
}));

function render(key: MessageKey, language: Language, vars?: Record<string, string | number>): string {
  let text = messages[language][key] ?? messages.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export function translate(key: MessageKey, vars?: Record<string, string | number>): string {
  return render(key, useLanguageStore.getState().language, vars);
}

export function useTranslate() {
  const language = useLanguageStore((state) => state.language);
  return (key: MessageKey, vars?: Record<string, string | number>) => render(key, language, vars);
}
